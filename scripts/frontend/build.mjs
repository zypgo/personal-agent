// Build the two typed adapters into self-contained browser modules. Python serves these checked-in
// outputs directly: installing/running the Python package never downloads JavaScript or runs Node.
import { createHash } from "node:crypto";
import { mkdtemp, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "vite";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const destination = join(root, "src/personal_agent/channels/web/static");
const check = process.argv.includes("--check");
const output = await mkdtemp(join(tmpdir(), "pa-frontend-build-"));
const entries = ["query", "markdown-parser"];
const bundledPackages = new Set();
try {
  await build({
    root,
    configFile: false,
    publicDir: false,
    logLevel: "warn",
    // Vite library mode intentionally leaves this expression for consumers by default. These
    // files are final browser assets, so remove development branches and all Node assumptions.
    define: { "process.env.NODE_ENV": JSON.stringify("production") },
    plugins: [{
      name: "bundled-license-inventory",
      generateBundle(_options, bundle) {
        for (const chunk of Object.values(bundle)) {
          if (chunk.type !== "chunk") continue;
          for (const id of chunk.moduleIds) {
            const match = id.replaceAll("\\", "/").match(/\/node_modules\/((?:@[^/]+\/)?[^/]+)/);
            if (match) bundledPackages.add(match[1]);
          }
        }
      },
    }],
    build: {
      outDir: output,
      emptyOutDir: false,
      target: "es2022",
      sourcemap: false,
      minify: "oxc",
      lib: {
        entry: Object.fromEntries(entries.map(name => [name, join(root, `frontend/${name}.ts`)])),
        formats: ["es"],
        fileName: (_format, name) => `${name}.js`,
      },
    },
  });
  const generated = await readdir(output);
  if (generated.length !== entries.length || generated.some(name => !entries.some(entry => name === `${entry}.js`))) {
    throw new Error("The frontend must build to exactly two self-contained adapters; add any new assets to the server and offline shell explicitly.");
  }
  for (const name of generated) {
    const contents = await readFile(join(output, name));
    if (check && !contents.equals(await readFile(join(destination, name)))) {
      throw new Error(`${name} is stale; run npm run build and commit the generated static modules.`);
    }
    if (!check) await writeFile(join(destination, name), contents);
    console.log(`${check ? "verified" : "built"} ${name}: ${contents.length} bytes (${createHash("sha256").update(contents).digest("hex").slice(0, 12)})`);
  }
  if (!bundledPackages.has("markdown-it") || !bundledPackages.has("@tanstack/query-core")) {
    throw new Error("The browser build did not include the expected mature adapters.");
  }
  let notices = "Bundled frontend dependency licenses\n\nGenerated by scripts/frontend/build.mjs from the modules actually included in query.js and markdown-parser.js.\n\n";
  for (const name of [...bundledPackages].sort()) {
    const directory = join(root, "node_modules", name);
    const metadata = JSON.parse(await readFile(join(directory, "package.json"), "utf8"));
    const license = (await readdir(directory)).sort().find(file => /^licen[cs]e(?:[.-]|$)/i.test(file));
    if (!license) throw new Error(`A license notice is required for bundled dependency ${name}.`);
    const repository = typeof metadata.repository === "string" ? metadata.repository : metadata.repository?.url;
    notices += `${name} ${metadata.version} (${metadata.license})\n${repository || metadata.homepage || ""}\n\n${(await readFile(join(directory, license), "utf8")).trim()}\n\n`;
  }
  notices = notices.trimEnd() + "\n";
  const noticePath = join(destination, "THIRD_PARTY_NOTICES.txt");
  if (check && notices !== await readFile(noticePath, "utf8")) {
    throw new Error("Bundled dependency notices are stale; run npm run build.");
  }
  if (!check) await writeFile(noticePath, notices);
  console.log(`${check ? "verified" : "built"} license notices for ${bundledPackages.size} bundled packages`);
} finally {
  await rm(output, { recursive: true, force: true });
}
